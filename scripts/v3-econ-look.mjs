// v3 econ: upgrade buttons in nearby at a printer (weapon first), the upgrade toast, big level badges, bag n/4; 1280×720
import { chromium } from 'playwright';
import { spawn } from 'child_process';
const dir = process.argv[2] || '.';
const out = process.argv[3] || '.';
const port = 4000 + Math.floor(Math.random() * 1000);
const srv = spawn('npx', ['vite', 'preview', '--port', String(port), '--strictPort'], { cwd: dir, stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(`http://localhost:${port}/?seed=3&still`);
await p.waitForTimeout(800);
const send = (c) => p.evaluate((c) => window.thaw.send(c), c);
const step = (s) => p.evaluate((s) => window.step(s), s);
for (const c of ['install map spool', 'install stepper relay', 'install spark finger', 'install thread bell', 'conjure bone lance', 'conjure pinhole eye', 'conjure nail psalm', 'conjure choir bell', 'conjure frost coat', 'conjure ember cell', 'conjure halo']) await send(c);
await p.evaluate(() => { const g = thaw.g; g.player.slots = 8; g.player.core = 20; });
await send('install pinhole eye');
await send('install bone lance');
await step(3);
await p.evaluate(() => document.querySelector('.kit-later')?.click());
await p.evaluate(() => { const g = thaw.g; g.ents.push({ id: 99999, kind: 'printer', x: g.player.x + 0.6, y: g.player.y, data: { far: 0, made: 0, greeted: true } }); g.player.inv.push({ kind: 'res', res: 'bone', n: 30 }, { kind: 'res', res: 'copper', n: 10 }, { kind: 'res', res: 'glass', n: 8 }); });
await step(0.5);
await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/v3e-nearby.png` });
const near = await p.evaluate(() => document.querySelector('.panel-near')?.innerText ?? null);
await send('print');
await p.evaluate(() => { const b = [...document.querySelectorAll('.panel-near button')].find((x) => x.dataset.cmd?.startsWith('upgrade')); b?.click(); });
await step(0.3);
await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/v3e-toast.png` });
const toast = await p.evaluate(() => document.querySelector('.toast')?.innerText ?? null);
await p.waitForTimeout(3000);
await send('upgrade bone lance');
await step(0.3);
await p.waitForTimeout(3200);
await step(0.3);
await p.screenshot({ path: `${out}/v3e-badges.png` });
const head = await p.evaluate(() => document.querySelector('.panel-inv .res')?.innerText ?? null);
const log = await p.evaluate(() => thaw.g.log.slice(-14).map((l) => l.map((s) => (typeof s === 'string' ? s : s.text)).join('')).join('\n'));
console.log(JSON.stringify({ near, toast, head }, null, 1));
console.log(log);
console.log('errors:', errs.join('\n'));
await b.close();
srv.kill();
