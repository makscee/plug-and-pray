// v3 modules: a duplicate upgrades (II on the tile and card), the bag of 4 asks what to recycle, `upgrade` at a printer; 1280×720
import { chromium } from 'playwright';
import { spawn } from 'child_process';
const dir = process.argv[2] || '.';
const out = process.argv[3] || '.';
const port = 4000 + Math.floor(Math.random() * 1000);
const srv = spawn('npx', ['vite', 'preview', '--port', String(port), '--strictPort'], { cwd: dir, stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(`http://localhost:${port}/?seed=3&still`);
await p.waitForTimeout(800);
const send = (c) => p.evaluate((c) => window.thaw.send(c), c);
const step = (s) => p.evaluate((s) => window.step(s), s);
for (const c of ['install map spool', 'install stepper relay', 'install spark finger', 'conjure nail psalm', 'conjure nail psalm', 'conjure spark finger', 'conjure ember iris', 'conjure choir bell', 'conjure bone lance', 'conjure frost coat']) await send(c);
await step(3);
await p.mouse.click(640, 360);
await step(0.5);
const tile = await p.$('.panel-inv .cell[data-mod="nail-psalm"]');
if (tile) await tile.hover();
await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/v3m-bag.png` });
const card = await p.evaluate(() => document.querySelector('.item-card')?.innerText ?? null);
await p.mouse.move(400, 300);
// a printer at hand, with resources: the menu lists upgrades, and one runs
await p.evaluate(() => { const g = thaw.g; g.ents.push({ id: 99999, kind: 'printer', x: g.player.x + 0.6, y: g.player.y, data: { far: 0, made: 0 } }); g.player.inv.push({ kind: 'res', res: 'bone', n: 20 }, { kind: 'res', res: 'copper', n: 10 }, { kind: 'res', res: 'glass', n: 6 }); });
await send('recycle frost coat');
await send('print');
await send('upgrade spark finger');
await step(0.5);
await p.screenshot({ path: `${out}/v3m-printer.png` });
const state = await p.evaluate(() => ({ inst: thaw.g.player.installed.map((i) => i.mod + ':' + (i.level ?? 1)), bag: thaw.g.player.inv.filter((i) => i.kind === 'mod').map((i) => i.mod + ':' + (i.level ?? 1)), log: thaw.g.log.slice(-14).map((l) => l.map((s) => (typeof s === 'string' ? s : s.text)).join('')) }));
console.log(JSON.stringify({ card, ...state }, null, 1));
console.log(errs.join('\n'));
await b.close();
srv.kill();
